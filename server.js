// ---------- GET /health ----------
app.get("/health", async (req, res) => {
  try {
    await pool.query("SELECT 1");
    res.status(200).json({ status: "ok", database: "connected" });
  } catch (error) {
    console.error("Health check failed:", error.message);
    res.status(503).json({ status: "error", database: "unavailable", message: "Database is not responding." });
  }
});

// ---------- Record routes ----------
app.use("/api/records", require("./routes/records"));

// ---------- Unknown routes -> JSON 404 ----------
app.use((req, res) => {
  res.status(404).json({ message: "Route not found." });
});

// ---------- Error handler (four parameters) ----------
app.use((error, req, res, next) => {
  if (res.headersSent) return next(error);

  // Malformed JSON, oversized body or other bad request from the body parser
  if (error.type === "entity.parse.failed" || error.status === 400) {
    return res.status(400).json({ message: "Malformed JSON in request body." });
  }
  if (error.type === "entity.too.large") {
    return res.status(400).json({ message: "Request body is too large." });
  }

  console.error("Unexpected error:", error);
  res.status(500).json({ message: "Something went wrong on the server." });
});

// ---------- Start ----------
const port = process.env.PORT || 3000;
app.listen(port, "0.0.0.0", () => {
  console.log(`Server listening on port ${port}`);
  // Create the table (and seed it the first time) once the server is up.
  pool.initDb().catch((error) => {
    console.error("Database setup failed:", error.message);
  });
});
